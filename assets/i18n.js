function normalizeText(text) {
  return text.replace(/\s+/g, ' ').trim();
}

function getTranslation(original, lang) {
  if (lang === 'fr') return original;
  const dict = AMAN_I18N[lang] || {};
  const key = normalizeText(original);
  return dict[key] || original;
}

function collectTextNodes(root = document.body) {
  const ignored = new Set(['SCRIPT', 'STYLE', 'NOSCRIPT', 'TEXTAREA']);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const parent = node.parentElement;
      if (!parent || ignored.has(parent.tagName)) return NodeFilter.FILTER_REJECT;
      if (parent.closest('#langSel')) return NodeFilter.FILTER_REJECT;
      if (!normalizeText(node.nodeValue)) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    }
  });
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  return nodes;
}

function initI18nNodes() {
  const previousNodes = window.__amanI18nNodes || [];
  const seenNodes = new WeakSet(previousNodes.map(item => item.node).filter(Boolean));
  const newNodes = collectTextNodes()
    .filter(node => !seenNodes.has(node))
    .map(node => ({ node, original: node.nodeValue }));
  window.__amanI18nNodes = previousNodes.concat(newNodes);

  const previousInputs = window.__amanI18nInputs || [];
  const seenInputs = new WeakSet(previousInputs.map(item => item.el).filter(Boolean));
  const newInputs = Array.from(document.querySelectorAll('input[placeholder], textarea[placeholder]'))
    .filter(el => !seenInputs.has(el))
    .map(el => ({ el, original: el.getAttribute('placeholder') || '' }));
  window.__amanI18nInputs = previousInputs.concat(newInputs);
}

function applyLanguage(lang) {
  initI18nNodes();
  document.documentElement.lang = lang;
  localStorage.setItem('aman_lang', lang);

  document.querySelectorAll('#langSel a').forEach(a => {
    a.classList.toggle('active', a.dataset.lang === lang);
  });

  for (const item of window.__amanI18nNodes) {
    const original = item.original;
    const leading = original.match(/^\s*/)?.[0] || '';
    const trailing = original.match(/\s*$/)?.[0] || '';
    const translated = getTranslation(original, lang);
    item.node.nodeValue = leading + translated + trailing;
  }

  for (const item of window.__amanI18nInputs || []) {
    item.el.setAttribute('placeholder', getTranslation(item.original, lang));
  }
}

function ensureLanguageSelector() {
  document.querySelectorAll('.lang-selector').forEach(sel => {
    sel.id = 'langSel';
    sel.innerHTML = `
      <a href="#" data-lang="fr">FR</a>
      <a href="#" data-lang="en">EN</a>
      <a href="#" data-lang="nl">NL</a>
    `;
  });
}

document.addEventListener('DOMContentLoaded', () => {
  ensureLanguageSelector();
  initI18nNodes();
  const saved = localStorage.getItem('aman_lang') || 'fr';

  document.querySelectorAll('#langSel a').forEach(a => {
    a.addEventListener('click', e => {
      e.preventDefault();
      applyLanguage(a.dataset.lang || 'fr');
    });
  });

  applyLanguage(saved);
});
